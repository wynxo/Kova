#!/usr/bin/env python3
"""Vendor a pinned subset of Lucide icons into a single SVG sprite.

Kova's frontend has no bundler and no package.json. Icons therefore cannot arrive as a
npm dependency that the build tree-shakes; they have to be checked in. Checking in the
whole of Lucide would be ~1600 files and several megabytes for the ~20 icons the UI
actually uses, so this script fetches a fixed list at a fixed version and emits one
sprite.

What it guarantees:

* **Pinned.** The version is a constant. Re-running the script at a later date produces
  the same bytes, and an icon cannot change under the UI without a commit.
* **Attributed.** Lucide is ISC licensed. The sprite carries the licence header and
  `docs/ICONS.md` records the version and source.
* **Safe.** Each file is checked for script content, `on*` handlers and external
  references before it is embedded. An upstream compromise should not become a stored
  XSS in a self-hosted app.
* **Deterministic.** Icons are listed alphabetically and written with `\\n` endings, so
  a re-run only shows up in git when the icon set really changed.

Usage:
    python scripts/vendor_icons.py            # write web_assets/vendor/icons.svg
    python scripts/vendor_icons.py --check    # fail if the file is stale
    python scripts/vendor_icons.py --list     # print the pinned icon set
"""

from __future__ import annotations

import argparse
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPRITE_PATH = ROOT / "web_assets" / "vendor" / "icons.svg"

# Bump deliberately, and re-run the script. Never resolve "latest" at build time.
LUCIDE_VERSION = "0.469.0"
LUCIDE_URL = "https://raw.githubusercontent.com/lucide-icons/lucide/{version}/icons/{name}.svg"

# The icons the UI needs, and nothing else. Keep this list alphabetical.
ICONS: tuple[str, ...] = (
    "check",
    "chevron-down",
    "chevron-right",
    "clock",
    "file-text",
    "plus",
    "search",
    "sparkles",
    "terminal",
    "x",
)

LICENCE = """\
<!--
  Lucide icons, vendored from https://github.com/lucide-icons/lucide at version {version}.
  ISC License. Copyright (c) for portions of Lucide are held by Cole Bemis 2013-2022,
  and the Lucide Contributors 2022.

  Generated by scripts/vendor_icons.py. Do not edit by hand: change the icon list or the
  pinned version and re-run the script. See docs/ICONS.md.
-->"""

# Attributes every symbol gets, so a caller cannot forget them and the icons inherit the
# current text colour instead of hard-coding one.
SYMBOL_ATTRS = (
    'fill="none" stroke="currentColor" stroke-width="1.75" '
    'stroke-linecap="round" stroke-linejoin="round"'
)

_FORBIDDEN = (
    re.compile(r"<script", re.IGNORECASE),
    re.compile(r"<foreignObject", re.IGNORECASE),
    re.compile(r"\son[a-z]+\s*=", re.IGNORECASE),
    re.compile(r"javascript:", re.IGNORECASE),
    re.compile(r"href\s*=\s*[\"']?(?!#)", re.IGNORECASE),
    re.compile(r"url\(\s*[\"']?(?!#)", re.IGNORECASE),
)


def fetch_icon(name: str, *, version: str = LUCIDE_VERSION) -> str:
    url = LUCIDE_URL.format(version=version, name=name)
    with urllib.request.urlopen(url, timeout=30) as response:  # noqa: S310 - fixed host
        return response.read().decode("utf-8")


def audit(name: str, svg: str) -> list[str]:
    """Reject anything a self-hosted app must not inline."""
    problems: list[str] = []
    for pattern in _FORBIDDEN:
        match = pattern.search(svg)
        if match:
            problems.append(f"{name}: contains forbidden {match.group(0)!r}")
    return problems


def to_symbol(name: str, svg: str) -> str:
    """Rewrite a Lucide `<svg>` file as a `<symbol>` with a stable id."""
    opening = re.search(r"<svg\b([^>]*)>", svg)
    if opening is None:
        raise ValueError(f"{name}: no <svg> element")
    view_box = re.search(r'viewBox="([^"]+)"', opening.group(1))
    if view_box is None:
        raise ValueError(f"{name}: no viewBox")

    inner = svg[opening.end() : svg.rindex("</svg>")]
    inner = re.sub(r"<!--.*?-->", "", inner, flags=re.DOTALL)
    inner = re.sub(r"<title>.*?</title>", "", inner, flags=re.DOTALL)
    inner = re.sub(r">\s+<", "><", inner).strip()

    return (
        f'  <symbol id="icon-{name}" viewBox="{view_box.group(1)}" {SYMBOL_ATTRS}>\n'
        f"    {inner}\n"
        f"  </symbol>"
    )


def render_sprite(fetcher=fetch_icon) -> str:
    problems: list[str] = []
    symbols: list[str] = []
    for name in sorted(ICONS):
        svg = fetcher(name)
        problems.extend(audit(name, svg))
        symbols.append(to_symbol(name, svg))
    if problems:
        raise ValueError("\n".join(problems))

    return "\n".join(
        [
            LICENCE.format(version=LUCIDE_VERSION),
            '<svg xmlns="http://www.w3.org/2000/svg" style="display:none" aria-hidden="true">',
            *symbols,
            "</svg>",
            "",
        ]
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the sprite is stale")
    parser.add_argument("--list", action="store_true", help="print the pinned icon set")
    args = parser.parse_args(argv)

    if args.list:
        print(f"lucide {LUCIDE_VERSION} ({len(ICONS)} icons)")
        for name in sorted(ICONS):
            print(f"  {name}")
        return 0

    if args.check:
        if not SPRITE_PATH.exists():
            print(f"FAIL {SPRITE_PATH.relative_to(ROOT)} is missing", file=sys.stderr)
            return 1
        if SPRITE_PATH.read_text(encoding="utf-8") != render_sprite():
            print(
                "FAIL sprite is stale: re-run python scripts/vendor_icons.py",
                file=sys.stderr,
            )
            return 1
        print(f"icons ok: {len(ICONS)} symbols at lucide {LUCIDE_VERSION}")
        return 0

    sprite = render_sprite()
    SPRITE_PATH.parent.mkdir(parents=True, exist_ok=True)
    SPRITE_PATH.write_text(sprite, encoding="utf-8")
    print(f"wrote {SPRITE_PATH.relative_to(ROOT)} ({len(sprite)} bytes, {len(ICONS)} icons)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
