import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const source = readFileSync('src/kova/web_assets/app.js', 'utf8');
const block = source.slice(source.indexOf('  let autostartBusy'), source.indexOf('  const scroll ='));
const nodes = Object.fromEntries(['settings','autostart-toggle','autostart-status','autostart-refresh'].map(id => [id, {addEventListener() {}}]));
let result = {available:true, enabled:true, stale:false};
let reject = false;
const calls = [];
const ctx = vm.createContext({$: id => nodes[id], api: async (...args) => { calls.push(args); if (reject) throw Error(); return result; }});
vm.runInContext(block, ctx);
await vm.runInContext('refreshAutostart()', ctx);
assert.equal(nodes['autostart-toggle'].checked, true);
assert.equal(nodes['autostart-toggle'].disabled, false);
result = {available:true, enabled:false, stale:true};
await vm.runInContext("refreshAutostart('off')", ctx);
assert.equal(calls.at(-1)[0], '/autostart/off');
assert.match(nodes['autostart-status'].textContent, /stale/);
assert.equal(nodes['autostart-toggle'].checked, false);
reject = true;
await vm.runInContext('refreshAutostart()', ctx);
assert.equal(nodes['autostart-toggle'].disabled, true);
assert.equal(nodes['autostart-toggle'].indeterminate, true);
assert.match(nodes['autostart-status'].textContent, /Could not confirm/);
reject = false;
result = {available:false, enabled:false};
await vm.runInContext('refreshAutostart()', ctx);
assert.equal(nodes['autostart-toggle'].disabled, true);
