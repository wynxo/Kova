"""Themes as data: what Kova ships, what a user installs, and how they resolve.

A theme is one JSON document shaped like ``design/theme.schema.json`` — never code.
The two built-in palettes live in the generated ``tokens.json`` beside this module,
so a theme file only lists what it changes and inherits everything else from the
base it extends. This is the server half of #174: discovery, structural validation
and merging. Editor imports and saves also check contrast through
``kova.theme_routes``.

Nothing here touches the browser. A theme is resolved on the server and handed to
a client as plain values, so a broken file can never reach a stylesheet.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

#: The palettes Kova ships, generated from ``design/tokens.json``.
BUILTIN: tuple[str, ...] = ("kova-dark", "kova-light")

#: The document generated by ``scripts/build_tokens.py`` next to the package.
TOKENS_PATH = Path(__file__).with_name("tokens.json")

APPEARANCES = ("dark", "light")
GROUPS = ("bg", "fg", "border", "accent", "status", "syntax")
_TOP_LEVEL = {
    "$schema", "id", "name", "version", "author", "description",
    "appearance", "extends", "tokens", "terminal", "background",
}
_ID = re.compile(r"^[a-z0-9][a-z0-9-]{1,39}$")
_SEMVER = re.compile(r"^\d+\.\d+\.\d+$")
_COLOUR = re.compile(r"^(#(?:[0-9a-fA-F]{3,4}|[0-9a-fA-F]{6}(?:[0-9a-fA-F]{2})?)|rgba?\([0-9.,%\s/]+\))$")

#: Backgrounds (#206). An image is one file in ``KOVA_HOME/themes/assets``:
#: a name only, never a path or URL, and one of these three types. Bytes are
#: capped so a theme cannot make the app fetch an arbitrarily large file.
BACKGROUND_TYPES = {".png": "image/png", ".jpg": "image/jpeg", ".webp": "image/webp"}
BACKGROUND_MAX_BYTES = 4 * 1024 * 1024
_BACKGROUND_FILE = re.compile(r"^[a-z0-9][a-z0-9._-]{0,63}\.(?:png|jpg|webp)$")
_BACKGROUND_KEYS = {
    "gradient": {"kind", "stops", "angle"},
    "image": {"kind", "file", "dim", "blur"},
    "noise": {"kind", "opacity"},
}
GRADIENT_DEFAULT_ANGLE = 160
IMAGE_DEFAULT_DIM = 0.55
IMAGE_DEFAULT_BLUR = 0
NOISE_DEFAULT_OPACITY = 0.06
NOISE_MAX_OPACITY = 0.2


class ThemeError(ValueError):
    """A theme file, or a request for one, did not validate."""


class ThemeAssetTooLarge(ThemeError):
    """A background image is valid in shape but larger than Kova will serve."""


# ------------------------------------------------------------------------- built-ins
def builtin_data() -> dict[str, Any]:
    """The generated token document's ``themes`` object, read fresh from disk."""
    try:
        text = TOKENS_PATH.read_text(encoding="utf-8")
    except OSError as exc:
        raise ThemeError(
            f"{TOKENS_PATH.name} is missing from the Kova package; "
            "run `python scripts/build_tokens.py`."
        ) from exc
    try:
        payload = json.loads(text)
    except json.JSONDecodeError as exc:
        raise ThemeError(
            f"{TOKENS_PATH.name} is not valid JSON ({exc.msg} at line {exc.lineno}); "
            "run `python scripts/build_tokens.py`."
        ) from exc
    themes = payload.get("themes") if isinstance(payload, dict) else None
    if not isinstance(themes, dict):
        raise ThemeError(
            f"{TOKENS_PATH.name} has no 'themes' object; run `python scripts/build_tokens.py`."
        )
    return themes


def _builtin(theme_id: str) -> dict[str, Any]:
    palette = builtin_data().get(theme_id)
    if not isinstance(palette, dict) or not isinstance(palette.get("tokens"), dict):
        raise ThemeError(
            f"The built-in theme {theme_id!r} is missing from {TOKENS_PATH.name}; "
            "run `python scripts/build_tokens.py`."
        )
    return palette


def display_name(theme_id: str) -> str:
    """``kova-dark`` -> ``Kova Dark``, for clients that show a name."""
    return " ".join(part.capitalize() for part in theme_id.split("-"))


def default_base(appearance: str) -> str:
    """The base a theme inherits from when it does not name one."""
    return "kova-dark" if appearance == "dark" else "kova-light"


def base_tokens(theme_id: str) -> dict[str, Any]:
    """One built-in palette, flattened, with its terminal colours under ``terminal``."""
    palette = _builtin(theme_id)
    tokens = dict(palette["tokens"])
    tokens["terminal"] = list(palette.get("terminal") or [])
    return tokens


# ------------------------------------------------------------------------ validation
def _is_colour(value: Any) -> bool:
    return isinstance(value, str) and bool(_COLOUR.match(value))


def _number(value: Any, low: float, high: float, field: str) -> float:
    if not isinstance(value, (int, float)) or isinstance(value, bool) or not low <= value <= high:
        raise ThemeError(f"background.{field} must be a number from {low} to {high}; got {value!r}.")
    return float(value)


def _background(value: Any) -> dict[str, Any]:
    """Validate one background object and return it with its defaults filled in.

    Three disjoint shapes (mirrored by the schema's ``oneOf``): a gradient of
    2-4 colours, a fine noise texture with an opacity, or one image file name
    plus dim and blur. Unknown keys are refused, so no shape can smuggle in a
    URL or a CSS fragment.
    """
    if not isinstance(value, dict):
        raise ThemeError("background must be an object.")
    kind = value.get("kind")
    if kind not in _BACKGROUND_KEYS:
        raise ThemeError("background.kind must be 'gradient', 'noise' or 'image'.")
    allowed = _BACKGROUND_KEYS[kind]
    unknown = sorted(set(value) - allowed)
    if unknown:
        raise ThemeError(
            f"background.{kind} has unexpected key{'s' if len(unknown) > 1 else ''}: "
            f"{', '.join(unknown)}."
        )

    if kind == "gradient":
        stops = value.get("stops")
        if not isinstance(stops, list) or not 2 <= len(stops) <= 4:
            raise ThemeError("background.stops must be 2-4 colours.")
        for index, colour in enumerate(stops):
            if not _is_colour(colour):
                raise ThemeError(
                    f"background.stops[{index}] must be a hex or rgb()/rgba() colour; got {colour!r}."
                )
        angle = value.get("angle", GRADIENT_DEFAULT_ANGLE)
        return {
            "kind": "gradient",
            "stops": list(stops),
            "angle": _number(angle, 0, 360, "angle"),
        }

    if kind == "noise":
        opacity = value.get("opacity", NOISE_DEFAULT_OPACITY)
        return {"kind": "noise", "opacity": _number(opacity, 0.02, NOISE_MAX_OPACITY, "opacity")}

    name = value.get("file")
    if not isinstance(name, str) or not _BACKGROUND_FILE.fullmatch(name):
        raise ThemeError(
            "background.file must be one file name in themes/assets "
            "(lowercase letters, digits, dots and hyphens; png, jpg or webp)."
        )
    dim = value.get("dim", IMAGE_DEFAULT_DIM)
    blur = value.get("blur", IMAGE_DEFAULT_BLUR)
    return {
        "kind": "image",
        "file": name,
        "dim": _number(dim, 0, 0.8, "dim"),
        "blur": _number(blur, 0, 24, "blur"),
    }


def _terminal(palette: Any) -> list[str]:
    if not isinstance(palette, list) or len(palette) != 16:
        raise ThemeError("terminal must be exactly 16 colours, in ANSI order 0-15.")
    for index, colour in enumerate(palette):
        if not _is_colour(colour):
            raise ThemeError(
                f"terminal[{index}] must be a hex or rgb()/rgba() colour; got {colour!r}."
            )
    return list(palette)


def validate(payload: Any) -> dict[str, Any]:
    """Check one theme document, raising :class:`ThemeError` with a sentence.

    This mirrors ``design/theme.schema.json``: the same keys, the same patterns and
    nothing else. Unknown groups or token names are refused rather than ignored, so
    a theme cannot quietly claim to change something it does not.
    """
    if not isinstance(payload, dict):
        raise ThemeError("A theme must be one JSON object.")
    unknown = sorted(set(payload) - _TOP_LEVEL)
    if unknown:
        raise ThemeError(
            f"Unexpected key{'s' if len(unknown) > 1 else ''}: {', '.join(unknown)}. "
            "A theme is data: no CSS, scripts or URLs."
        )
    for field in ("id", "name", "version", "appearance"):
        if field not in payload:
            raise ThemeError(f"Missing required key {field!r}.")

    theme_id = payload["id"]
    if not isinstance(theme_id, str) or not _ID.fullmatch(theme_id):
        raise ThemeError(
            f"id {theme_id!r} must be lowercase letters, digits and hyphens (2-40 characters)."
        )
    name = payload["name"]
    if not isinstance(name, str) or not 1 <= len(name) <= 60:
        raise ThemeError("name must be a string of 1-60 characters.")
    version = payload["version"]
    if not isinstance(version, str) or not _SEMVER.fullmatch(version):
        raise ThemeError(f"version {version!r} must look like 1.0.0.")
    appearance = payload["appearance"]
    if appearance not in APPEARANCES:
        raise ThemeError(
            f"appearance must be one of {', '.join(APPEARANCES)}; got {appearance!r}."
        )
    for field, limit in (("author", 80), ("description", 280)):
        if field in payload:
            value = payload[field]
            if not isinstance(value, str) or len(value) > limit:
                raise ThemeError(f"{field} must be a string of at most {limit} characters.")

    base_id = payload.get("extends") or default_base(appearance)
    if base_id not in BUILTIN:
        raise ThemeError(f"extends must be one of {', '.join(BUILTIN)}; got {base_id!r}.")
    base = base_tokens(base_id)

    tokens = payload.get("tokens", {})
    if not isinstance(tokens, dict):
        raise ThemeError("tokens must be an object of semantic groups.")
    for group, values in tokens.items():
        if group not in GROUPS:
            raise ThemeError(
                f"tokens.{group} is not a semantic group; use one of {', '.join(GROUPS)}."
            )
        if not isinstance(values, dict):
            raise ThemeError(f"tokens.{group} must be an object of token names to colours.")
        for key, value in values.items():
            token = f"{group}.{key}"
            if token not in base:
                raise ThemeError(f"tokens.{token} is not a token of {base_id}.")
            if not _is_colour(value):
                raise ThemeError(
                    f"tokens.{token} must be a hex or rgb()/rgba() colour; got {value!r}."
                )

    if "terminal" in payload:
        _terminal(payload["terminal"])
    if "background" in payload:
        _background(payload["background"])
    return payload


def load_file(path: Path | str) -> dict[str, Any]:
    """Read and validate one theme file, naming itself in any error."""
    path = Path(path)
    try:
        text = path.read_text(encoding="utf-8")
    except UnicodeError as exc:
        raise ThemeError(f"{path.name} is not a UTF-8 theme JSON file.") from exc
    except OSError as exc:
        raise ThemeError(f"Could not read {path.name}: {exc.strerror or exc}") from exc
    try:
        payload = json.loads(text)
    except json.JSONDecodeError as exc:
        raise ThemeError(
            f"{path.name} is not valid JSON ({exc.msg} at line {exc.lineno})."
        ) from exc
    try:
        theme = validate(payload)
    except ThemeError as exc:
        raise ThemeError(f"{path.name}: {exc}") from exc
    if theme["id"] != path.stem:
        raise ThemeError(
            f"{path.name}: id {theme['id']!r} must match the file name ({path.stem!r})."
        )
    return theme


# --------------------------------------------------------------------------- merging
def resolve(theme: dict[str, Any]) -> dict[str, Any]:
    """The theme's tokens laid over the base it extends, flattened.

    Keys are ``group.token`` (``accent.default``), the same names ``tokens.css``
    uses as custom properties; the 16-role terminal palette is under ``terminal``.
    """
    base = base_tokens(theme.get("extends") or default_base(theme["appearance"]))
    for group, values in (theme.get("tokens") or {}).items():
        for key, value in values.items():
            base[f"{group}.{key}"] = value
    if theme.get("terminal"):
        base["terminal"] = list(theme["terminal"])
    return base


def _summary(theme: dict[str, Any]) -> dict[str, Any]:
    return {
        "id": theme["id"],
        "name": theme["name"],
        "version": theme["version"],
        "appearance": theme["appearance"],
        "extends": theme.get("extends") or default_base(theme["appearance"]),
    }


def theme_dir(home: Path | str) -> Path:
    """Where a user's theme files live: ``KOVA_HOME/themes``."""
    return Path(home) / "themes"


def assets_dir(home: Path | str) -> Path:
    """Where a theme's background images live: ``KOVA_HOME/themes/assets``."""
    return theme_dir(home) / "assets"


def normalise_background(value: Any) -> dict[str, Any] | None:
    """The background with defaults filled in, or ``None`` when absent."""
    return None if value is None else _background(value)


def background_asset(home: Path | str, name: str) -> Path:
    """Resolve one servable background image, or raise :class:`ThemeError`.

    The name is checked before the filesystem is touched. The resolved path
    must stay inside ``themes/assets`` (a symlink cannot point elsewhere) and
    the file must be one of the three image types and within the size cap.
    """
    if not isinstance(name, str) or not _BACKGROUND_FILE.fullmatch(name):
        raise ThemeError("Not a theme background image name.")
    directory = assets_dir(home)
    try:
        resolved = (directory / name).resolve(strict=True)
    except (OSError, RuntimeError) as exc:
        raise ThemeError("No such theme background image.") from exc
    root = directory.resolve()
    if root not in resolved.parents or not resolved.is_file():
        raise ThemeError("No such theme background image.")
    if resolved.suffix not in BACKGROUND_TYPES:
        raise ThemeError("Theme backgrounds are png, jpg or webp.")
    if resolved.stat().st_size > BACKGROUND_MAX_BYTES:
        raise ThemeAssetTooLarge(
            f"Background images must be at most {BACKGROUND_MAX_BYTES // (1024 * 1024)} MiB."
        )
    return resolved


def discover(home: Path | str) -> list[dict[str, Any]]:
    """Every theme Kova can offer: the built-ins, then the user's files.

    A file that does not validate is listed with its error instead of being hidden,
    so `kova themes list` can say what is wrong with it.
    """
    entries: list[dict[str, Any]] = [
        {
            "id": theme_id,
            "name": display_name(theme_id),
            "version": None,
            "appearance": "dark" if theme_id == "kova-dark" else "light",
            "extends": None,
            "source": "built-in",
            "error": None,
        }
        for theme_id in BUILTIN
    ]
    directory = theme_dir(home)
    if not directory.is_dir():
        return entries
    for path in sorted(directory.glob("*.json")):
        try:
            theme = load_file(path)
        except ThemeError as exc:
            entries.append({
                "id": path.stem,
                "name": None,
                "version": None,
                "appearance": None,
                "extends": None,
                "source": str(path),
                "error": str(exc),
            })
            continue
        entries.append({**_summary(theme), "source": str(path), "error": None})
    return entries


def get(theme_id: str, home: Path | str) -> dict[str, Any]:
    """One theme with its tokens resolved, or :class:`ThemeError` naming the problem."""
    if not isinstance(theme_id, str) or not _ID.fullmatch(theme_id):
        raise ThemeError(f"{theme_id!r} is not a theme id.")
    if theme_id in BUILTIN:
        tokens = base_tokens(theme_id)
        terminal = tokens.pop("terminal")
        return {
            "id": theme_id,
            "name": display_name(theme_id),
            "version": None,
            "appearance": "dark" if theme_id == "kova-dark" else "light",
            "extends": None,
            "source": "built-in",
            "tokens": tokens,
            "terminal": terminal,
            "background": None,
        }
    path = theme_dir(home) / f"{theme_id}.json"
    if not path.is_file():
        raise ThemeError(
            f"No theme {theme_id!r}. Theme files live in {theme_dir(home)}; "
            "run `kova themes list`."
        )
    theme = load_file(path)
    tokens = resolve(theme)
    terminal = tokens.pop("terminal")
    return {
        **_summary(theme),
        "source": str(path),
        "tokens": tokens,
        "terminal": terminal,
        "background": normalise_background(theme.get("background")),
    }


# ------------------------------------------------------------------ the browser chrome
#: The theme preference's fixed choices and the built-in each one paints with.
#: ``system`` follows the device, which a web manifest cannot express, so the
#: manifest uses the dark base: the same one ``index.html`` paints first.
CHOICES: dict[str, str] = {"system": "kova-dark", "dark": "kova-dark", "light": "kova-light"}


def chrome_colours(choice: str | None, home: Path | str) -> dict[str, str]:
    """The window colours for a theme preference: ``theme_color`` and ``background_color``.

    Both are the theme's ``bg.base``, so the title bar, the splash screen and the page
    behind them are one surface. A preference naming a theme file that is missing or
    broken falls back to the dark base rather than failing the manifest.
    """
    theme_id = CHOICES.get(choice or "system", choice or "kova-dark")
    try:
        tokens = get(theme_id, home)["tokens"]
    except ThemeError:
        tokens = get("kova-dark", home)["tokens"]
    base = tokens["bg.base"]
    return {"theme_color": base, "background_color": base}


